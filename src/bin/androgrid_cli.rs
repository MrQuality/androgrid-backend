//! AndroGrid Operator Management CLI and Cluster Observability Binary
//!
//! Provides operators with command line management for task submission,
//! worker node inventory queries, task status tracking, and cancellation.
//!
//! Traces to: AG-SPEC-2026-V2, [REQ-OP-001], [REQ-OP-004], [INV-002], [NFR-SEC-001], [NFR-PERF-001]

