/// Maps integer thermal status to Android PowerManager thermal status badge string.
fn thermal_status_badge(status: u32) -> &'static str {
    match status {
        0 => "NONE",
        1 => "LIGHT",
        2 => "MODERATE",
        3 => "SEVERE",
        4 => "CRITICAL",
        5 => "EMERGENCY",
        6 => "SHUTDOWN",
        _ => "UNKNOWN",
    }
}

#[derive(Serialize)]
struct CancelOutput {
    task_id: String,
    cancelled: bool,
    message: String,
}

#[derive(Serialize)]
struct PairOutput {
    pairing_token: String,
    cluster_endpoint: String,
    ca_fingerprint: String,
    node_id: Option<String>,
    expires_at_epoch_seconds: u64,
    pairing_payload_json: String,
    output_png: Option<String>,
}

fn task_state_to_string(state: i32) -> &'static str {
    match TaskState::try_from(state) {
        Ok(TaskState::Pending) => "PENDING",
        Ok(TaskState::Leased) => "LEASED",
        Ok(TaskState::Running) => "RUNNING",
        Ok(TaskState::Completed) => "COMPLETED",
        Ok(TaskState::Failed) => "FAILED",
        Ok(TaskState::Preempted) => "PREEMPTED",
        Ok(TaskState::TimedOut) => "TIMED_OUT",
        _ => "UNSPECIFIED",
    }
}

