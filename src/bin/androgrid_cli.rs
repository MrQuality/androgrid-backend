#[derive(Parser, Debug)]
#[command(
    name = "androgrid-cli",
    about = "AndroGrid Operator Management CLI and Cluster Observability",
    version = "0.1.0"
)]
struct Cli {
    /// gRPC control plane endpoint
    #[arg(
        long,
        global = true,
        default_value = "https://127.0.0.1:50051",
        env = "ANDROGRID_ENDPOINT"
    )]
    endpoint: String,

    /// Path to root CA PEM certificate for mTLS
    #[arg(long, global = true, env = "ANDROGRID_CA_CERT")]
    ca_cert: Option<PathBuf>,

    /// Path to operator client PEM certificate for mTLS
    #[arg(long, global = true, env = "ANDROGRID_CLIENT_CERT")]
    client_cert: Option<PathBuf>,

    /// Path to operator client private key PEM for mTLS
    #[arg(long, global = true, env = "ANDROGRID_CLIENT_KEY")]
    client_key: Option<PathBuf>,

    /// Output format: text or json
    #[arg(long, global = true, default_value = "text", value_parser = ["text", "json"])]
    format: String,

    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand, Debug)]
enum Commands {
    /// Validate and package a WebAssembly module with JSON deployment manifest
    /// Traces to: [INV-006], [REQ-OP-003]
    Pack {
        /// Path to WebAssembly module bytecode (.wasm)
        #[arg(long)]
        wasm: PathBuf,

        /// Exported entrypoint symbol name (default: _start)
        #[arg(long, default_value = "_start")]
        entrypoint: String,

        /// Optional output path for manifest JSON or packaged artifact bundle
        #[arg(long)]
        output: Option<PathBuf>,
    },

    /// Enqueue a new compute task to the cluster
    Submit {
        /// Explicit task identifier (autogenerated if omitted)
        #[arg(long)]
        task_id: Option<String>,

        /// Path to WebAssembly module bytecode (.wasm)
        #[arg(long, conflicts_with = "shell")]
        wasm: Option<PathBuf>,

        /// Exported entrypoint symbol name (default: _start)
        #[arg(long, default_value = "_start")]
        entrypoint: String,

        /// Retain in-band raw bytecode in gRPC message (disables decoupled distribution)
        #[arg(long)]
        inline: bool,

        /// Shell command string to execute
        #[arg(long, conflicts_with = "wasm")]
        shell: Option<String>,

        /// Execute shell command with root privileges (requires rooted node)
        #[arg(long, requires = "shell")]
        root: bool,

        /// Task execution timeout in seconds (default: 30)
        #[arg(long, default_value_t = 30)]
        timeout: u32,

        /// Force execution on unmetered Wi-Fi only
        #[arg(long)]
        requires_unmetered: bool,

        /// Decoupled artifact download URL for pre-cached distribution
        #[arg(long)]
        artifact_url: Option<String>,

        /// Environment variables in KEY=VALUE format
        #[arg(long, value_parser = parse_key_val)]
        env: Vec<(String, String)>,
    },

    /// Query the status and output of a specific task
    Status {
        /// Task identifier
        task_id: String,
    },

    /// List registered worker nodes and their hardware capabilities
    Nodes,

    /// Cancel a scheduled or active task
    Cancel {
        /// Task identifier
        task_id: String,
    },

    /// Generate an ephemeral device pairing token and interactive terminal QR code
    /// Traces to: [INV-002], [NFR-SEC-001], [REQ-OP-001]
    Pair {
        /// Explicit node identifier to bind to this pairing token (optional)
        #[arg(long)]
        node_id: Option<String>,

        /// Pairing token lifetime in seconds (default: 300)
        #[arg(long, default_value_t = 300)]
        expires_in: u32,

        /// Subject Alternative Name (SAN) or public host/IP of the orchestrator
        #[arg(long)]
        san: Option<String>,

        /// Optional output file path to save QR code as PNG image
        #[arg(long)]
        output_png: Option<PathBuf>,
    },

    /// Execute distributed parallel compute benchmark across cluster worker nodes
    /// Traces to: [INV-005], [INV-006], [NFR-PERF-001], [REQ-OP-004]
    Benchmark {
        /// Workload identifier (default: image-processor)
        #[arg(long, default_value = "image-processor")]
        workload: String,

        /// Path to input image file (JPEG or PNG)
        #[arg(long)]
        input: PathBuf,

        /// Number of geometric tiles to partition image into (default: 16)
        #[arg(long, default_value_t = 16)]
        tiles: u32,

        /// Path to write reconstructed composite output image
        #[arg(long)]
        output: PathBuf,

        /// Image filter operation (sobel, blur, downscale, equalize, grayscale, invert)
        #[arg(long, default_value = "sobel")]
        filter: String,

        /// Maximum concurrent tasks to dispatch (default: 4)
        #[arg(long, default_value_t = 4)]
        concurrency: usize,

        /// Task execution timeout in seconds per tile (default: 60)
        #[arg(long, default_value_t = 60)]
        timeout: u32,

        /// Enforce execution on unmetered Wi-Fi only
        #[arg(long)]
        requires_unmetered: bool,

        /// Path to custom WebAssembly module bytecode (.wasm)
        #[arg(long)]
        wasm: Option<PathBuf>,

        /// Run simulated local benchmark without connecting to remote cluster
        #[arg(long)]
        dry_run: bool,
    },

    /// Interactive real-time terminal cluster monitor
    /// Traces to: [INV-004], [INV-005], [NFR-REL-001]
    Top {
        /// Polling refresh interval in seconds (default: 1)
        #[arg(long, default_value_t = 1)]
        refresh_rate: u64,
    },
}

/// Parses KEY=VALUE command-line strings into pairs.
fn parse_key_val(s: &str) -> Result<(String, String), String> {
    s.split_once('=')
        .map(|(k, v)| (k.trim().to_string(), v.trim().to_string()))
        .ok_or_else(|| format!("Invalid environment variable format '{s}': expected KEY=VALUE"))
}

