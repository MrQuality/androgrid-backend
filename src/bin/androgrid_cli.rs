async fn create_channel(
    endpoint: &str,
    ca_cert: Option<&Path>,
    client_cert: Option<&Path>,
    client_key: Option<&Path>,
) -> Result<tonic::transport::Channel, Box<dyn std::error::Error>> {
    let mut endpoint_builder = tonic::transport::Endpoint::from_shared(endpoint.to_string())?;

    if let (Some(ca_path), Some(cert_path), Some(key_path)) = (ca_cert, client_cert, client_key) {
        let ca_pem = tokio::fs::read(ca_path).await?;
        let cert_pem = tokio::fs::read(cert_path).await?;
        let key_pem = tokio::fs::read(key_path).await?;

        let host_part = endpoint
            .trim_start_matches("https://")
            .trim_start_matches("http://")
            .split(':')
            .next()
            .unwrap_or("localhost");
        let domain = if host_part.is_empty() || host_part == "127.0.0.1" {
            "localhost"
        } else {
            host_part
        };

        let tls_config = build_client_mtls_config(&cert_pem, &key_pem, &ca_pem, domain);
        endpoint_builder = endpoint_builder.tls_config(tls_config)?;
    }

    let channel = endpoint_builder.connect().await?;
    Ok(channel)
}

/// Extracts a fallback `--san` `host:port` from a CLI `--endpoint` URL when the endpoint
/// targets a non-loopback, routable address. Loopback and unspecified addresses return `""`.
fn default_san_from_endpoint(endpoint: &str) -> String {
    let stripped = androgrid_backend::pairing::strip_uri_scheme(endpoint);
    let host = if let Some(rest) = stripped.strip_prefix('[') {
        rest.split(']').next().unwrap_or("")
    } else if stripped.matches(':').count() == 1 {
        stripped.split(':').next().unwrap_or("")
    } else {
        stripped.as_str()
    };

    if matches!(
        host,
        "" | "127.0.0.1" | "localhost" | "0.0.0.0" | "::1" | "::"
    ) {
        String::new()
    } else {
        stripped
    }
}

/// Runs the interactive terminal observability UI event loop.
///
/// Traces to: [INV-004], [INV-005], [NFR-REL-001]
async fn run_top(
    mut client: AdminServiceClient<tonic::transport::Channel>,
    endpoint: &str,
    refresh_rate_secs: u64,
) -> Result<(), Box<dyn std::error::Error>> {
    let _guard = TerminalGuard::init()?;
    let backend = ratatui::backend::CrosstermBackend::new(std::io::stdout());
    let mut terminal = ratatui::Terminal::new(backend)?;

    let mut app = TuiApp::new(endpoint.to_string());

    let tick_rate = std::time::Duration::from_secs(refresh_rate_secs.max(1));
    let mut last_fetch = std::time::Instant::now() - tick_rate;

    loop {
        if last_fetch.elapsed() >= tick_rate {
            if let Ok(res_nodes) = client.list_worker_nodes(ListWorkerNodesRequest {}).await {
                if let Ok(res_tasks) = client
                    .list_tasks(ListTasksRequest { state_filter: 0 })
                    .await
                {
                    app.update_from_nodes_and_tasks(
                        res_nodes.into_inner().nodes,
                        res_tasks.into_inner().tasks,
                    );
                }
            }
            last_fetch = std::time::Instant::now();
        }

        terminal.draw(|f| app.render(f))?;

        if crossterm::event::poll(std::time::Duration::from_millis(200))? {
            if let crossterm::event::Event::Key(key) = crossterm::event::read()? {
                if let Some(action) = app.handle_key(key) {
                    match action {
                        TuiAction::Quit => break,
                        TuiAction::CancelTask(task_id) => {
                            match client
                                .cancel_task(CancelTaskRequest {
                                    task_id: task_id.clone(),
                                })
                                .await
                            {
                                Ok(_) => app.set_status(format!("Task '{task_id}' cancelled")),
                                Err(e) => app.set_status(format!("Cancel failed: {}", e.message())),
                            }
                            last_fetch = std::time::Instant::now() - tick_rate;
                        }
                        TuiAction::GeneratePairingToken => {
                            match client
                                .generate_pairing_token(GeneratePairingTokenRequest {
                                    node_id: String::new(),
                                    expires_in_seconds: 300,
                                    san: default_san_from_endpoint(endpoint),
                                })
                                .await
                            {
                                Ok(res) => {
                                    let inner = res.into_inner();
                                    app.show_pairing_info(format!(
                                        "Token: {}\nCluster Endpoint: {}\nExpires in: 300s",
                                        inner.pairing_token, inner.cluster_endpoint
                                    ));
                                }
                                Err(e) => {
                                    app.set_status(format!("Pairing failed: {}", e.message()))
                                }
                            }
                        }
                        TuiAction::Refresh => {
                            last_fetch = std::time::Instant::now() - tick_rate;
                        }
                    }
                }
            }
        }

        if app.should_quit {
            break;
        }
    }

    Ok(())
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let matches = Cli::command().get_matches();
    let ca_cert_from_cli = matches.value_source("ca_cert") == Some(ValueSource::CommandLine);
    let cli = Cli::from_arg_matches(&matches)?;

    if let Commands::Pack {
        wasm,
        entrypoint,
        output,
    } = cli.command
    {
        let (manifest, written_path) =
            ArtifactPackager::pack(&wasm, &entrypoint, output.as_deref())
                .map_err(|e| format!("Packaging failed: {e}"))?;

        let pack_output = PackOutput {
            name: manifest.name,
            entrypoint: manifest.entrypoint,
            artifact_sha256: manifest.artifact_sha256,
            size_bytes: manifest.size_bytes,
            engine: manifest.engine,
            wasi_version: manifest.wasi_version,
            manifest_path: written_path.map(|p| p.display().to_string()),
        };

        if cli.format == "json" {
            println!("{}", serde_json::to_string_pretty(&pack_output)?);
        } else {
            println!("Workload Package Created:");
            println!("  Name:        {}", pack_output.name);
            println!("  Entrypoint:  {}", pack_output.entrypoint);
            println!("  SHA-256:     {}", pack_output.artifact_sha256);
            println!("  Size:        {} bytes", pack_output.size_bytes);
            println!("  Runtime:     {}", pack_output.engine);
            println!("  WASI Spec:   {}", pack_output.wasi_version);
            if let Some(path) = pack_output.manifest_path {
                println!("  Manifest:    {}", path);
            }
        }
        return Ok(());
    }

    if let Commands::Benchmark {
        workload: _,
        input,
        tiles,
        output,
        filter,
        concurrency,
        timeout,
        requires_unmetered,
        wasm,
        dry_run,
    } = cli.command
    {
        let parsed_filter =
            BenchmarkFilter::from_str_name(&filter).unwrap_or(BenchmarkFilter::Sobel);
        let config = BenchmarkConfig {
            input_path: input,
            output_path: output,
            tiles,
            filter: parsed_filter,
            wasm_path: wasm.clone(),
            timeout_seconds: timeout,
            concurrency,
            requires_unmetered,
            dry_run,
        };

        let dispatcher = BenchmarkDispatcher::new(config);
        let (_composite, metrics) = if dry_run {
            dispatcher.run_simulated(concurrency).await?
        } else {
            let channel = create_channel(
                &cli.endpoint,
                cli.ca_cert.as_deref(),
                cli.client_cert.as_deref(),
                cli.client_key.as_deref(),
            )
            .await?;
            let wasm_bytes = if let Some(p) = wasm {
                Some(tokio::fs::read(&p).await?)
            } else {
                None
            };
            dispatcher.run_cluster(channel, wasm_bytes).await?
        };

        if cli.format == "json" {
            println!("{}", serde_json::to_string_pretty(&metrics)?);
        } else {
            println!("{}", metrics.format_summary());
        }
        return Ok(());
    }

    if let Commands::Cert { action } = cli.command {
        return handle_cert_command(
            action,
            cli.ca_cert.as_deref(),
            ca_cert_from_cli,
            &cli.format,
        );
    }

    let channel = create_channel(
        &cli.endpoint,
        cli.ca_cert.as_deref(),
        cli.client_cert.as_deref(),
        cli.client_key.as_deref(),
    )
    .await?;

    let mut client = AdminServiceClient::new(channel);

    match cli.command {
        Commands::Pack { .. } => unreachable!(),
        Commands::Benchmark { .. } => unreachable!(),
        Commands::Cert { .. } => unreachable!(),

        Commands::Group { action } => {
            handle_group_command(&mut client, action, &cli.format).await?;
        }

        Commands::Top { refresh_rate } => {
            run_top(client, &cli.endpoint, refresh_rate).await?;
        }

        Commands::Submit {
            task_id,
            wasm,
            entrypoint,
            inline,
            shell,
            root,
            timeout,
            requires_unmetered,
            artifact_url,
            env,
        } => {
            let actual_task_id = task_id.unwrap_or_else(|| {
                let millis = SystemTime::now()
                    .duration_since(SystemTime::UNIX_EPOCH)
                    .unwrap_or_default()
                    .as_millis();
                format!("task_{millis}")
            });

            let (engine, wasm_bytecode, shell_command, artifact_sha256, resolved_artifact_url) =
                if let Some(wasm_path) = wasm {
                    let bytecode = tokio::fs::read(&wasm_path).await.map_err(|e| {
                        format!(
                            "Failed to read WASM bytecode from {}: {e}",
                            wasm_path.display()
                        )
                    })?;

                    // Validate WASI and compute SHA-256
                    let meta = WasiValidator::validate(&bytecode, &entrypoint)
                        .map_err(|e| format!("WASI validation failed: {e}"))?;

                    let sha256_hex = meta.artifact_sha256;

                    // External HTTP artifact_url is deprecated; workers resolve artifacts via mTLS FetchArtifact
                    if artifact_url.is_some() {
                        return Err(
                            "--artifact-url is deprecated and unsupported: omit --artifact-url so the CLI uploads the module via UploadArtifact for mTLS FetchArtifact resolution (or pass --inline for small payloads)".into()
                        );
                    }
                    if !inline {
                        // Register artifact with orchestrator over AdminService channel [NFR-PERF-001], [REQ-OP-003]
                        client
                            .upload_artifact(UploadArtifactRequest {
                                bytecode: bytecode.clone(),
                                expected_sha256: sha256_hex.clone(),
                            })
                            .await?;
                    }

                    let effective_bytecode = if inline {
                        bytecode
                    } else {
                        Vec::new() // Decoupled: sub-kilobyte gRPC control plane payload [NFR-PERF-001]
                    };

                    (
                        ExecutionEngine::WasmWasi as i32,
                        effective_bytecode,
                        String::new(),
                        sha256_hex,
                        String::new(),
                    )
                } else if let Some(cmd) = shell {
                    let engine = if root {
                        ExecutionEngine::RootShell as i32
                    } else {
                        ExecutionEngine::ToyboxUser as i32
                    };
                    (engine, Vec::new(), cmd, String::new(), String::new())
                } else {
                    return Err(
                        "Either --wasm <FILE> or --shell <COMMAND> must be specified.".into(),
                    );
                };

            let env_vars: HashMap<String, String> = env.into_iter().collect();

            #[allow(deprecated)]
            let task_spec = TaskSpec {
                task_id: actual_task_id.clone(),
                run_attempt: 1,
                engine,
                timeout_seconds: timeout,
                entrypoint,
                env_vars,
                wasm_bytecode,
                shell_command,
                artifact_sha256,
                requires_unmetered,
                artifact_url: resolved_artifact_url,
                group_id: String::new(),
                group_epoch: 0,
            };

            let response = client
                .submit_task(SubmitTaskRequest {
                    task: Some(task_spec),
                })
                .await?
                .into_inner();

            let output = SubmitOutput {
                accepted: response.accepted,
                task_id: response.task_id,
                message: response.message,
            };

            if cli.format == "json" {
                println!("{}", serde_json::to_string_pretty(&output)?);
            } else {
                println!("Task Submission Result:");
                println!("  Task ID:  {}", output.task_id);
                println!("  Accepted: {}", output.accepted);
                println!("  Message:  {}", output.message);
            }
        }

        Commands::Status { task_id } => {
            let res = client
                .get_task_status(GetTaskStatusRequest {
                    task_id: task_id.clone(),
                })
                .await?
                .into_inner();

            let stdout_str = String::from_utf8_lossy(&res.stdout_bytes).to_string();
            let stderr_str = String::from_utf8_lossy(&res.stderr_bytes).to_string();

            let output = TaskStatusOutput {
                task_id: res.task_id,
                state: task_state_to_string(res.state).to_string(),
                active_attempt: res.active_attempt,
                exit_code: res.exit_code,
                stdout: stdout_str,
                stderr: stderr_str,
                error_code: res.error_code,
                error_message: res.error_message,
                execution_duration_ms: res.execution_duration_ms,
            };

            if cli.format == "json" {
                println!("{}", serde_json::to_string_pretty(&output)?);
            } else {
                println!("Task Status Report:");
                println!("  Task ID:   {}", output.task_id);
                println!("  State:     {}", output.state);
                println!("  Attempt:   {}", output.active_attempt);
                println!("  Exit Code: {}", output.exit_code);
                println!("  Duration:  {} ms", output.execution_duration_ms);
                if !output.error_code.is_empty() {
                    println!(
                        "  Error:     {} - {}",
                        output.error_code, output.error_message
                    );
                }
                if !output.stdout.is_empty() {
                    println!("  Stdout:\n{}", output.stdout);
                }
                if !output.stderr.is_empty() {
                    println!("  Stderr:\n{}", output.stderr);
                }
            }
        }

        Commands::Nodes => {
            let res = client
                .list_worker_nodes(ListWorkerNodesRequest {})
                .await?
                .into_inner();

            let mut node_outputs = Vec::new();
            for node in res.nodes {
                let caps = node.capabilities.unwrap_or_default();
                let transport = match caps.current_transport {
                    1 => "Wi-Fi LAN",
                    2 => "Cellular WAN",
                    _ => "Unknown",
                };
                let thermal_badge = thermal_status_badge(caps.thermal_status);
                node_outputs.push(WorkerNodeOutput {
                    node_id: node.node_id,
                    cpu_cores: caps.cpu_cores,
                    ram_mb: caps.total_ram_bytes / (1024 * 1024),
                    os_version: caps.os_version,
                    abi: caps.abi,
                    is_rooted: caps.is_rooted,
                    is_metered: caps.is_metered,
                    transport: transport.to_string(),
                    battery_temperature_celsius: caps.battery_temperature_celsius,
                    thermal_status: thermal_badge.to_string(),
                    client_version: node.client_version,
                });
            }

            if cli.format == "json" {
                println!("{}", serde_json::to_string_pretty(&node_outputs)?);
            } else {
                println!("Registered Worker Nodes (Total: {}):", node_outputs.len());
                if node_outputs.is_empty() {
                    println!("  (No worker nodes currently registered)");
                } else {
                    println!(
                        "{:<20} {:<6} {:<10} {:<12} {:<12} {:<8} {:<10} {:<10} {:<14}",
                        "NODE ID",
                        "CORES",
                        "RAM (MB)",
                        "OS VERSION",
                        "ABI",
                        "ROOTED",
                        "TEMP (°C)",
                        "THERMAL",
                        "TRANSPORT"
                    );
                    println!("{}", "-".repeat(108));
                    for n in node_outputs {
                        let temp_str = if n.battery_temperature_celsius <= 0 {
                            "N/A".to_string()
                        } else {
                            format!("{}°C", n.battery_temperature_celsius)
                        };
                        println!(
                            "{:<20} {:<6} {:<10} {:<12} {:<12} {:<8} {:<10} {:<10} {:<14}",
                            n.node_id,
                            n.cpu_cores,
                            n.ram_mb,
                            n.os_version,
                            n.abi,
                            if n.is_rooted { "YES" } else { "NO" },
                            temp_str,
                            n.thermal_status,
                            n.transport
                        );
                    }
                }
            }
        }

        Commands::Cancel { task_id } => {
            let res = client
                .cancel_task(CancelTaskRequest {
                    task_id: task_id.clone(),
                })
                .await?
                .into_inner();

            let output = CancelOutput {
                task_id,
                cancelled: res.cancelled,
                message: res.message,
            };

            if cli.format == "json" {
                println!("{}", serde_json::to_string_pretty(&output)?);
            } else {
                println!("Task Cancellation Result:");
                println!("  Task ID:   {}", output.task_id);
                println!("  Cancelled: {}", output.cancelled);
                println!("  Message:   {}", output.message);
            }
        }

        Commands::Pair {
            node_id,
            expires_in,
            san,
            output_png,
        } => {
            let effective_san = san.unwrap_or_else(|| default_san_from_endpoint(&cli.endpoint));
            let res = client
                .generate_pairing_token(GeneratePairingTokenRequest {
                    node_id: node_id.unwrap_or_default(),
                    expires_in_seconds: expires_in,
                    san: effective_san,
                })
                .await?
                .into_inner();

            let target_node_id = if res.node_id.is_empty() {
                None
            } else {
                Some(res.node_id.clone())
            };

            let png_path_str = if let Some(ref path) = output_png {
                export_png(&res.pairing_payload_json, path)
                    .map_err(|e| format!("Failed to export QR code PNG: {e}"))?;
                Some(path.display().to_string())
            } else {
                None
            };

            let output = PairOutput {
                pairing_token: res.pairing_token.clone(),
                cluster_endpoint: res.cluster_endpoint.clone(),
                ca_fingerprint: res.ca_fingerprint.clone(),
                node_id: target_node_id.clone(),
                expires_at_epoch_seconds: res.expires_at_epoch_seconds,
                pairing_payload_json: res.pairing_payload_json.clone(),
                output_png: png_path_str.clone(),
            };

            if cli.format == "json" {
                println!("{}", serde_json::to_string_pretty(&output)?);
            } else {
                let qr_code = render_ansi_qr(&res.pairing_payload_json)
                    .map_err(|e| format!("Failed to render ANSI QR code: {e}"))?;

                print_banner();
                println!("Scan this QR code from the AndroGrid Android worker application:\n");
                println!("{qr_code}\n");
                println!("--------------------------------------------------------------------------------");
                println!("Pairing Details (Manual Fallback):");
                println!("  Endpoint:       {}", res.cluster_endpoint);
                println!("  CA Fingerprint: {}", res.ca_fingerprint);
                println!("  Pairing Token:  {}", res.pairing_token);
                if let Some(ref id) = target_node_id {
                    println!("  Bound Node ID:  {}", id);
                } else {
                    println!("  Bound Node ID:  (unbound: any new device)");
                }
                println!(
                    "  Expires At:     epoch {} (TTL {}s)",
                    res.expires_at_epoch_seconds, expires_in
                );
                if let Some(ref p) = png_path_str {
                    println!("  QR Image PNG:   {}", p);
                }
                println!("--------------------------------------------------------------------------------");
                println!("Raw Scannable Payload:");
                println!("{}", res.pairing_payload_json);
                println!("================================================================================");
            }
        }
    }

    Ok(())
}

/// Executes offline cluster PKI lifecycle commands (`cert init`, `cert issue ...`).
fn handle_cert_command(
    action: CertCommands,
    global_ca_cert: Option<&Path>,
    ca_cert_from_cli: bool,
    format: &str,
) -> Result<(), Box<dyn std::error::Error>> {
    match action {
        CertCommands::Init {
            out,
            san,
            no_default_sans,
            ca_days,
            days,
            admin_cn,
            force,
        } => {
            let summary = cert_init(&PkiInitConfig {
                out_dir: out,
                extra_sans: san,
                no_default_sans,
                ca_days,
                days,
                admin_cn,
                force,
            })?;
            print_cert_summary(&summary, format, None)?;
        }
        CertCommands::Issue { target } => {
            match target {
                CertIssueCommands::Server {
                    ca_dir,
                    ca_key,
                    out,
                    san,
                    no_default_sans,
                    days,
                    force,
                } => {
                    let ca_source =
                        resolve_ca_source(ca_dir, global_ca_cert, ca_cert_from_cli, ca_key)?;
                    let summary = cert_issue_server(&PkiIssueServerConfig {
                        ca_source,
                        out_dir: out,
                        extra_sans: san,
                        no_default_sans,
                        days,
                        force,
                    })?;
                    print_cert_summary(
                    &summary,
                    format,
                    Some("Restart androgrid-backend to load the rotated server certificate and key."),
                )?;
                }
                CertIssueCommands::Admin {
                    ca_dir,
                    ca_key,
                    out,
                    cn,
                    days,
                    force,
                } => {
                    let ca_source =
                        resolve_ca_source(ca_dir, global_ca_cert, ca_cert_from_cli, ca_key)?;
                    let summary = cert_issue_admin(&PkiIssueAdminConfig {
                        ca_source,
                        out_dir: out,
                        cn,
                        days,
                        force,
                    })?;
                    print_cert_summary(&summary, format, None)?;
                }
                CertIssueCommands::Csr {
                    csr,
                    node_id,
                    ca_dir,
                    ca_key,
                    out,
                    ca_out,
                    days,
                    force,
                } => {
                    let ca_source =
                        resolve_ca_source(ca_dir, global_ca_cert, ca_cert_from_cli, ca_key)?;
                    let summary = cert_issue_csr(&PkiIssueCsrConfig {
                        ca_source,
                        csr_path: csr,
                        node_id,
                        out_path: out,
                        ca_out_path: ca_out,
                        days,
                        force,
                    })?;
                    print_cert_summary(&summary, format, None)?;
                }
            }
        }
    }
    Ok(())
}

fn resolve_ca_source(
    ca_dir: Option<PathBuf>,
    global_ca_cert: Option<&Path>,
    ca_cert_from_cli: bool,
    ca_key: Option<PathBuf>,
) -> Result<CaSource, Box<dyn std::error::Error>> {
    if let Some(key_path) = ca_key {
        if ca_dir.is_some() {
            return Err("Cannot combine --ca-dir with --ca-key".into());
        }
        let cert_path = global_ca_cert
            .ok_or("Explicit --ca-key requires --ca-cert (or ANDROGRID_CA_CERT) to be specified")?;
        Ok(CaSource::Files {
            ca_cert: cert_path.to_path_buf(),
            ca_key: key_path,
        })
    } else if ca_cert_from_cli {
        Err("Explicit --ca-cert requires --ca-key (or omit --ca-cert to use --ca-dir)".into())
    } else {
        Ok(CaSource::Dir(
            ca_dir.unwrap_or_else(|| PathBuf::from("./pki")),
        ))
    }
}

fn print_cert_summary(
    summary: &PkiOperationSummary,
    format: &str,
    notice: Option<&str>,
) -> Result<(), Box<dyn std::error::Error>> {
    if format == "json" {
        println!("{}", serde_json::to_string_pretty(summary)?);
        if let Some(msg) = notice {
            eprintln!("[!] Notice: {msg}");
        }
    } else {
        println!("[+] {}", summary.action);
        println!("    CA SHA-256: {}", summary.ca_fingerprint);
        if let Some(ref cn) = summary.cn {
            println!("    CN:         {cn}");
        }
        if let Some(ref node_id) = summary.node_id {
            println!("    Node ID:    {node_id}");
        }
        if !summary.sans.is_empty() {
            println!("    SANs:       {}", summary.sans.join(", "));
        }
        println!(
            "    Validity:   {} days ({} -> {})",
            summary.days_valid, summary.not_before, summary.not_after
        );
        println!("    Files:");
        for file in &summary.files {
            println!("      - {file}");
        }
        if let Some(msg) = notice {
            println!("[!] Notice: {msg}");
        }
    }
    Ok(())
}

struct GroupTemplateArgs {
    wasm: Option<PathBuf>,
    entrypoint: String,
    shell: Option<String>,
    root: bool,
    timeout: u32,
    requires_unmetered: bool,
    env: Vec<(String, String)>,
}

async fn resolve_group_template(
    client: &mut AdminServiceClient<tonic::transport::Channel>,
    args: GroupTemplateArgs,
) -> Result<TaskTemplate, Box<dyn std::error::Error>> {
    let GroupTemplateArgs {
        wasm,
        entrypoint,
        shell,
        root,
        timeout,
        requires_unmetered,
        env,
    } = args;
    let (engine, shell_command, artifact_sha256) = if let Some(wasm_path) = wasm {
        let bytecode = tokio::fs::read(&wasm_path).await.map_err(|e| {
            format!(
                "Failed to read WASM bytecode from {}: {e}",
                wasm_path.display()
            )
        })?;
        let meta = WasiValidator::validate(&bytecode, &entrypoint)
            .map_err(|e| format!("WASI validation failed: {e}"))?;
        let sha256_hex = meta.artifact_sha256;
        client
            .upload_artifact(UploadArtifactRequest {
                bytecode,
                expected_sha256: sha256_hex.clone(),
            })
            .await?;
        (ExecutionEngine::WasmWasi as i32, String::new(), sha256_hex)
    } else if let Some(cmd) = shell {
        let engine = if root {
            ExecutionEngine::RootShell as i32
        } else {
            ExecutionEngine::ToyboxUser as i32
        };
        (engine, cmd, String::new())
    } else {
        return Err("Either --wasm <FILE> or --shell <COMMAND> must be specified.".into());
    };

    Ok(TaskTemplate {
        engine,
        timeout_seconds: timeout,
        entrypoint,
        env_vars: env.into_iter().collect(),
        artifact_sha256,
        shell_command,
        requires_unmetered,
    })
}

fn build_partitions(count: u32) -> Vec<TaskPartitionSpec> {
    (0..count)
        .map(|idx| TaskPartitionSpec {
            env_overrides: HashMap::from([("PARTITION_INDEX".to_string(), idx.to_string())]),
        })
        .collect()
}

fn parse_group_state_filter(state: Option<&str>) -> Result<i32, String> {
    match state.map(str::to_ascii_lowercase).as_deref() {
        None => Ok(TaskGroupState::Unspecified as i32),
        Some("active") => Ok(TaskGroupState::Active as i32),
        Some("draining") => Ok(TaskGroupState::Draining as i32),
        Some("completed") => Ok(TaskGroupState::Completed as i32),
        Some("failed") => Ok(TaskGroupState::Failed as i32),
        Some("cancelled") => Ok(TaskGroupState::Cancelled as i32),
        Some(other) => Err(format!(
            "Invalid --state '{}'; expected one of: active, draining, completed, failed, cancelled",
            other
        )),
    }
}

fn format_group_status_output(
    res: &androgrid_backend::GetTaskGroupStatusResponse,
    include_tasks: bool,
    format: &str,
) -> String {
    if format == "json" {
        let mut obj = serde_json::json!({
            "group_id": res.group_id,
            "current_epoch": res.current_epoch,
            "state": task_group_state_to_string(res.state),
            "total_tasks": res.total_tasks,
            "pending_tasks": res.pending_tasks,
            "leased_tasks": res.leased_tasks,
            "running_tasks": res.running_tasks,
            "completed_tasks": res.completed_tasks,
            "failed_tasks": res.failed_tasks,
            "timed_out_tasks": res.timed_out_tasks,
            "cancelled_tasks": res.cancelled_tasks,
            "preempted_tasks": res.preempted_tasks,
            "previous_epoch_draining_tasks": res.previous_epoch_draining_tasks,
        });
        if include_tasks {
            let tasks: Vec<_> = res
                .tasks
                .iter()
                .map(|t| {
                    serde_json::json!({
                        "task_id": t.task_id,
                        "state": task_state_to_string(t.state),
                        "run_attempt": t.run_attempt,
                        "assigned_node_id": t.assigned_node_id,
                        "exit_code": t.exit_code,
                        "execution_duration_ms": t.execution_duration_ms,
                        "error_message": t.error_message,
                    })
                })
                .collect();
            obj["tasks"] = serde_json::Value::Array(tasks);
        }
        return obj.to_string();
    }

    let mut out = format!(
        "TaskGroup {} [epoch={}, state={}]: total={}, pending={}, leased={}, running={}, completed={}, failed={}, timed_out={}, cancelled={}, preempted={}, draining_prev={}",
        res.group_id,
        res.current_epoch,
        task_group_state_to_string(res.state),
        res.total_tasks,
        res.pending_tasks,
        res.leased_tasks,
        res.running_tasks,
        res.completed_tasks,
        res.failed_tasks,
        res.timed_out_tasks,
        res.cancelled_tasks,
        res.preempted_tasks,
        res.previous_epoch_draining_tasks
    );
    if include_tasks {
        for t in &res.tasks {
            out.push_str(&format!(
                "\n  - {} [{}] attempt={} node={} exit_code={}",
                t.task_id,
                task_state_to_string(t.state),
                t.run_attempt,
                if t.assigned_node_id.is_empty() {
                    "-"
                } else {
                    t.assigned_node_id.as_str()
                },
                t.exit_code
            ));
        }
    }
    out
}

async fn handle_group_command(
    client: &mut AdminServiceClient<tonic::transport::Channel>,
    action: GroupCommands,
    format: &str,
) -> Result<(), Box<dyn std::error::Error>> {
    match action {
        GroupCommands::Submit {
            group_id,
            partitions,
            wasm,
            entrypoint,
            shell,
            root,
            timeout,
            requires_unmetered,
            env,
        } => {
            let template = resolve_group_template(
                client,
                GroupTemplateArgs {
                    wasm,
                    entrypoint,
                    shell,
                    root,
                    timeout,
                    requires_unmetered,
                    env,
                },
            )
            .await?;
            let res = client
                .submit_task_group(SubmitTaskGroupRequest {
                    group: Some(TaskGroupSpec {
                        group_id,
                        template: Some(template),
                        partitions: build_partitions(partitions),
                    }),
                })
                .await?
                .into_inner();
            if format == "json" {
                println!(
                    "{}",
                    serde_json::json!({
                        "accepted": res.accepted,
                        "group_id": res.group_id,
                        "group_epoch": res.group_epoch,
                        "total_tasks": res.total_tasks,
                        "message": res.message,
                    })
                );
            } else {
                println!(
                    "TaskGroup {} accepted (epoch={}, total_tasks={})",
                    res.group_id, res.group_epoch, res.total_tasks
                );
            }
        }
        GroupCommands::Replace {
            group_id,
            expected_epoch,
            strategy,
            partitions,
            wasm,
            entrypoint,
            shell,
            root,
            timeout,
            requires_unmetered,
            env,
        } => {
            let strat = match strategy.to_ascii_lowercase().as_str() {
                "immediate" => ReplaceStrategy::Immediate as i32,
                "drain" => ReplaceStrategy::Drain as i32,
                other => {
                    return Err(format!(
                        "Unsupported strategy '{}'; expected 'immediate' or 'drain'",
                        other
                    )
                    .into());
                }
            };
            let template = resolve_group_template(
                client,
                GroupTemplateArgs {
                    wasm,
                    entrypoint,
                    shell,
                    root,
                    timeout,
                    requires_unmetered,
                    env,
                },
            )
            .await?;
            let res = client
                .replace_task_group(ReplaceTaskGroupRequest {
                    group_id,
                    expected_epoch,
                    template: Some(template),
                    partitions: build_partitions(partitions),
                    strategy: strat,
                })
                .await?
                .into_inner();
            if format == "json" {
                println!(
                    "{}",
                    serde_json::json!({
                        "accepted": res.accepted,
                        "group_id": res.group_id,
                        "new_epoch": res.new_epoch,
                        "state": task_group_state_to_string(res.state),
                        "cancelled_tasks": res.cancelled_tasks,
                        "draining_tasks": res.draining_tasks,
                        "created_tasks": res.created_tasks,
                    })
                );
            } else {
                println!(
                    "TaskGroup {} replaced (epoch={}, state={}, created={}, cancelled={}, draining={})",
                    res.group_id,
                    res.new_epoch,
                    task_group_state_to_string(res.state),
                    res.created_tasks,
                    res.cancelled_tasks,
                    res.draining_tasks
                );
            }
        }
        GroupCommands::Cancel {
            group_id,
            expected_epoch,
        } => {
            let res = client
                .cancel_task_group(CancelTaskGroupRequest {
                    group_id,
                    expected_epoch,
                })
                .await?
                .into_inner();
            if format == "json" {
                println!(
                    "{}",
                    serde_json::json!({
                        "cancelled": res.cancelled,
                        "group_id": res.group_id,
                        "epoch": res.epoch,
                        "cancelled_tasks": res.cancelled_tasks,
                    })
                );
            } else {
                println!(
                    "TaskGroup {} cancelled (epoch={}, cancelled_tasks={})",
                    res.group_id, res.epoch, res.cancelled_tasks
                );
            }
        }
        GroupCommands::Status {
            group_id,
            include_tasks,
        } => {
            let res = client
                .get_task_group_status(GetTaskGroupStatusRequest {
                    group_id,
                    include_tasks,
                })
                .await?
                .into_inner();
            println!(
                "{}",
                format_group_status_output(&res, include_tasks, format)
            );
        }
        GroupCommands::List { state } => {
            let state_filter = parse_group_state_filter(state.as_deref())
                .map_err(|msg| std::io::Error::new(std::io::ErrorKind::InvalidInput, msg))?;
            let res = client
                .list_task_groups(ListTaskGroupsRequest { state_filter })
                .await?
                .into_inner();
            if format == "json" {
                let items: Vec<_> = res
                    .groups
                    .iter()
                    .map(|g| {
                        serde_json::json!({
                            "group_id": g.group_id,
                            "current_epoch": g.current_epoch,
                            "state": task_group_state_to_string(g.state),
                            "total_tasks": g.total_tasks,
                            "completed_tasks": g.completed_tasks,
                            "failed_tasks": g.failed_tasks,
                            "cancelled_tasks": g.cancelled_tasks,
                        })
                    })
                    .collect();
                println!("{}", serde_json::to_string_pretty(&items)?);
            } else if res.groups.is_empty() {
                println!("No TaskGroups registered.");
            } else {
                for g in &res.groups {
                    println!(
                        "{}  epoch={}  state={}  {}/{} completed",
                        g.group_id,
                        g.current_epoch,
                        task_group_state_to_string(g.state),
                        g.completed_tasks,
                        g.total_tasks
                    );
                }
            }
        }
    }
    Ok(())
}

